// Generates everything in build/ from tokens/. Run: npm run build
// Never edit build/ by hand: CI rebuilds it and fails if it differs.
import fs from "node:fs";
import path from "node:path";
import { ROOT, load, cssValue, varName, get } from "./lib/tokens.mjs";

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const OUT = path.join(ROOT, "build");
const HEADER = `Generated by scripts/build.mjs from tokens/ (mise-en-place v${pkg.version}). Do not edit.`;

const { foundations, themes } = load();
fs.mkdirSync(path.join(OUT, "mermaid"), { recursive: true });

// 1. CSS custom properties -------------------------------------------------
const block = (selector, tokens, indent = "") =>
  `${indent}${selector} {\n` +
  tokens.map((t) => `${indent}  ${varName(t)}: ${cssValue(t)};`).join("\n") +
  `\n${indent}}\n`;

const css = [
  `/* ${HEADER}\n   Themes: light (default), dark (follows the system unless data-theme is set), paper (opt-in).\n   Usage: <html data-theme="paper">, or leave data-theme unset to follow the system. */\n`,
  block(":root", foundations),
  block(':root,\n[data-theme="light"]', themes.light),
  `@media (prefers-color-scheme: dark) {\n${block(":root:not([data-theme])", themes.dark, "  ")}}\n`,
  block('[data-theme="dark"]', themes.dark),
  block('[data-theme="paper"]', themes.paper),
].join("\n");
fs.writeFileSync(path.join(OUT, "tokens.css"), css);

// 2. Resolved JSON: flat, plain values, for scripts and AI assistants ---------
const flat = (list) => Object.fromEntries(list.map((t) => [t.path.join("."), cssValue(t)]));
const resolved = {
  $comment: HEADER,
  version: pkg.version,
  foundations: flat(foundations),
  themes: Object.fromEntries(Object.entries(themes).map(([n, list]) => [n, flat(list)])),
};
fs.writeFileSync(path.join(OUT, "tokens.resolved.json"), JSON.stringify(resolved, null, 2) + "\n");

// 3. Mermaid: paper theme only. See docs/decisions/0004-mermaid-on-github.md ---
const p = themes.paper;
const c = (dotted) => cssValue(get(p, dotted));
const bg = c("color.background.default");
const ink = c("color.text.default");
const subtle = c("color.text.subtle");
const accent = c("color.accent");
const border = c("color.border.default");
const line = c("color.diagram.line");
const font = cssValue(get(foundations, "font.family.system"));

const themeVariables = {
  background: bg,
  fontFamily: font,
  fontSize: "16px",
  primaryColor: bg,
  primaryTextColor: ink,
  primaryBorderColor: ink,
  secondaryColor: bg,
  secondaryTextColor: ink,
  secondaryBorderColor: subtle,
  tertiaryColor: bg,
  tertiaryTextColor: ink,
  tertiaryBorderColor: border,
  lineColor: line,
  textColor: ink,
  titleColor: ink,
  nodeTextColor: ink,
  clusterBkg: bg,
  clusterBorder: border,
  edgeLabelBackground: bg,
  noteBkgColor: bg,
  noteTextColor: ink,
  noteBorderColor: border,
  actorBkg: bg,
  actorBorder: ink,
  actorTextColor: ink,
  actorLineColor: line,
  signalColor: line,
  signalTextColor: line,
  labelBoxBkgColor: bg,
  labelBoxBorderColor: border,
  labelTextColor: ink,
  loopTextColor: line,
};
fs.writeFileSync(
  path.join(OUT, "mermaid", "theme.json"),
  JSON.stringify({ $comment: HEADER, theme: "base", themeVariables }, null, 2) + "\n",
);

const classDefs = [
  `classDef built fill:${bg},stroke:${ink},stroke-width:1.5px,color:${ink}`,
  `classDef planned fill:${bg},stroke:${subtle},stroke-width:1.5px,stroke-dasharray:6 4,color:${subtle}`,
  `classDef focus fill:${bg},stroke:${accent},stroke-width:3px,color:${ink}`,
];

const yaml = (obj, indent) =>
  Object.entries(obj).map(([k, v]) => `${indent}${k}: ${JSON.stringify(v)}`).join("\n");

const frontmatter = `---\nconfig:\n  theme: base\n  themeVariables:\n${yaml(themeVariables, "    ")}\n---`;

fs.writeFileSync(
  path.join(OUT, "mermaid", "starter.mmd"),
  `${frontmatter}
%% ${HEADER}
%% Copy everything above "flowchart" as is, then replace the example below.
flowchart LR
  ${classDefs.join("\n  ")}

  subgraph core["Core"]
    a["Built component"]:::built
    b["Planned component"]:::planned
  end
  c["Component in focus"]:::focus

  a --> b
  a -- "label" --> c
`,
);

console.log("build/ updated: tokens.css, tokens.resolved.json, mermaid/theme.json, mermaid/starter.mmd");

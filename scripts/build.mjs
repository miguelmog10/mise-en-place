// Generates everything in build/ from tokens/. Run: npm run build
// Never edit build/ by hand: CI rebuilds it and fails if it differs.
import fs from "node:fs";
import path from "node:path";
import { ROOT, DEFAULT_FAMILY, load, cssValue, varName, get } from "./lib/tokens.mjs";

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const OUT = path.join(ROOT, "build");
const HEADER = `Generated by scripts/build.mjs from tokens/ (mise-en-place v${pkg.version}). Do not edit.`;

const { foundations, families } = load();
const others = Object.keys(families).filter((f) => f !== DEFAULT_FAMILY);
fs.mkdirSync(path.join(OUT, "mermaid"), { recursive: true });

// 1. CSS custom properties -------------------------------------------------
// The default family (editorial) applies with no attribute, exactly as in v0.1.
// Other families apply under data-family="<name>", on <html> or on any subtree.
// See docs/decisions/0009-two-theme-families.md.
const block = (selector, tokens, indent = "") =>
  `${indent}${selector} {\n` +
  tokens.map((t) => `${indent}  ${varName(t)}: ${cssValue(t)};`).join("\n") +
  `\n${indent}}\n`;

const def = families[DEFAULT_FAMILY];
const notOthers = others.map((f) => `:not([data-family="${f}"])`).join("");
const cssParts = [
  `/* ${HEADER}
   Theme families: ${Object.keys(families).join(", ")}. Editorial is the default.
   Editorial: light (default), dark (follows the system unless data-theme is set), paper (opt-in).
     <html>, <html data-theme="dark">, <html data-theme="paper">
   Screen: light and dark, following the system unless data-theme is set.
     <html data-family="screen">, <html data-family="screen" data-theme="dark">
   data-family and data-theme also work on a subtree, such as one section of a page. */\n`,
  block(":root", [...foundations, ...def.tokens]),
  block(':root,\n[data-theme="light"]', def.themes.light),
  `@media (prefers-color-scheme: dark) {\n${block(`:root:not([data-theme])${notOthers}`, def.themes.dark, "  ")}}\n`,
  ...Object.entries(def.themes).filter(([n]) => n !== "light").map(([n, list]) => block(`[data-theme="${n}"]`, list)),
];
for (const family of others) {
  const { tokens, themes } = families[family];
  const scope = `[data-family="${family}"]`;
  cssParts.push(
    block(scope, [...tokens, ...themes.light]),
    `@media (prefers-color-scheme: dark) {\n${block(`${scope}:not([data-theme])`, themes.dark, "  ")}}\n`,
    ...Object.entries(themes).map(([n, list]) =>
      block(`${scope}[data-theme="${n}"],\n${scope} [data-theme="${n}"]`, list)),
  );
}
fs.writeFileSync(path.join(OUT, "tokens.css"), cssParts.join("\n"));

// 2. Resolved JSON: flat, plain values, for scripts and AI assistants ---------
const flat = (list) => Object.fromEntries(list.map((t) => [t.path.join("."), cssValue(t)]));
const themesOf = (f) => Object.fromEntries(Object.entries(families[f].themes).map(([n, list]) => [n, flat(list)]));
const resolved = {
  $comment: `${HEADER} "shared" and "families" are the full picture. "foundations" and "themes" are the default family (${DEFAULT_FAMILY}) in the v0.1 shape, kept for compatibility.`,
  version: pkg.version,
  defaultFamily: DEFAULT_FAMILY,
  shared: flat(foundations),
  families: Object.fromEntries(Object.keys(families).map((f) => [f, { foundations: flat(families[f].tokens), themes: themesOf(f) }])),
  foundations: flat([...foundations, ...def.tokens]),
  themes: themesOf(DEFAULT_FAMILY),
};
fs.writeFileSync(path.join(OUT, "tokens.resolved.json"), JSON.stringify(resolved, null, 2) + "\n");

// 3. Mermaid ---------------------------------------------------------------
// Editorial paper: for GitHub and any Markdown host (ADR 0004).
// Screen light and dark: for pages that render Mermaid in the browser and swap the skin (ADR 0010).
const sys = cssValue(get(foundations, "font.family.system"));
const markWidth = cssValue(get(foundations, "border.width.mark"));

function mermaid(list, { font, nodeFill, plannedStroke, focusWidth }) {
  const c = (dotted) => cssValue(get(list, dotted));
  const bg = c("color.background.default");
  const ink = c("color.text.default");
  const subtle = c("color.text.subtle");
  const accent = c("color.accent");
  const border = c("color.border.default");
  const line = c("color.diagram.line");
  const fill = nodeFill ? c(nodeFill) : bg;
  const planned = c(plannedStroke);
  const themeVariables = {
    background: bg,
    fontFamily: font,
    fontSize: "16px",
    primaryColor: fill,
    primaryTextColor: ink,
    primaryBorderColor: ink,
    secondaryColor: fill,
    secondaryTextColor: ink,
    secondaryBorderColor: planned,
    tertiaryColor: bg,
    tertiaryTextColor: ink,
    tertiaryBorderColor: border,
    lineColor: line,
    textColor: ink,
    titleColor: ink,
    nodeTextColor: ink,
    clusterBkg: bg,
    clusterBorder: border,
    edgeLabelBackground: bg,
    noteBkgColor: fill,
    noteTextColor: ink,
    noteBorderColor: border,
    actorBkg: fill,
    actorBorder: ink,
    actorTextColor: ink,
    actorLineColor: line,
    signalColor: line,
    // Message and loop text in ink: on the paper rect of the sequence pattern it passes 4.5:1 (diagrams.md).
    signalTextColor: ink,
    labelBoxBkgColor: fill,
    labelBoxBorderColor: border,
    labelTextColor: ink,
    loopTextColor: ink,
  };
  const classDefs = {
    built: `classDef built fill:${fill},stroke:${ink},stroke-width:${markWidth},color:${ink}`,
    planned: `classDef planned fill:${fill},stroke:${planned},stroke-width:${markWidth},stroke-dasharray:6 4,color:${subtle}`,
    focus: `classDef focus fill:${fill},stroke:${accent},stroke-width:${focusWidth},color:${ink}`,
  };
  const yaml = (obj, indent) =>
    Object.entries(obj).map(([k, v]) => `${indent}${k}: ${JSON.stringify(v)}`).join("\n");
  // Mermaid 11 reads fontFamily from the config root, not from themeVariables.
  // Kept in both places: the themeVariables copy is harmless and older versions read it.
  const frontmatter = `---\nconfig:\n  theme: base\n  fontFamily: ${JSON.stringify(font)}\n  themeVariables:\n${yaml(themeVariables, "    ")}\n---`;
  return { bg, config: { theme: "base", fontFamily: font, themeVariables }, classDefs, frontmatter };
}

const writeTheme = (file, m, note) =>
  fs.writeFileSync(
    path.join(OUT, "mermaid", file),
    JSON.stringify({ $comment: `${HEADER} ${note}`, ...m.config, classDefs: m.classDefs, frontmatter: m.frontmatter }, null, 2) + "\n",
  );

// Editorial paper (GitHub). Thick accent border for focus: GitHub cannot draw a single edge.
const paper = mermaid(families.editorial.themes.paper, {
  font: sys, plannedStroke: "color.text.subtle", focusWidth: "3px",
});
writeTheme("theme.json", paper, "Editorial paper theme for Mermaid on GitHub. Use theme, fontFamily and themeVariables as the Mermaid config.");

// Screen light and dark (browser). Nodes on ticket paper, planned outlines in border.strong.
// Mermaid cannot draw a single top edge, so focus keeps a 3px accent border here (diagrams.md).
const screenFont = cssValue(get(families.screen.tokens, "font.family.sans"));
for (const mode of ["light", "dark"]) {
  const m = mermaid(families.screen.themes[mode], {
    font: screenFont, nodeFill: "color.surface.default", plannedStroke: "color.border.strong", focusWidth: "3px",
  });
  writeTheme(`theme-screen-${mode}.json`, m,
    `Screen ${mode} theme for Mermaid rendered in the browser. Replace a diagram's frontmatter with "frontmatter" and its classDef built|planned|focus lines with "classDefs".`);
}

const classLines = Object.values(paper.classDefs).join("\n  ");
fs.writeFileSync(
  path.join(OUT, "mermaid", "starter.mmd"),
  `${paper.frontmatter}
%% ${HEADER}
%% Copy everything above "flowchart" as is, then replace the example below.
%% Keep the legend whenever a diagram shows more than one status.
flowchart LR
  ${classLines}

  subgraph core["Core"]
    a["Built component"]:::built
    b["Planned component"]:::planned
  end
  c["Component in focus"]:::focus

  a -.-> b
  a -- "label" --> c

  subgraph legend["Legend"]
    direction LR
    lb1["Built"]:::built --> lb2["Built"]:::built
    lp1["Planned"]:::planned -.-> lp2["Planned"]:::planned
  end
`,
);

const [r, g, b] = paper.bg.match(/\w\w/g).map((h) => parseInt(h, 16));
fs.writeFileSync(
  path.join(OUT, "mermaid", "sequence-starter.mmd"),
  `${paper.frontmatter}
%% ${HEADER}
%% Sequence diagrams draw message text on the host page. Three habits keep it readable on white and dark:
%% 1. Wrap every message in the paper rect below, so text sits on paper.
%% 2. Message and loop text are ink (set in the frontmatter).
%% 3. Use participant, never actor: an actor's name is drawn on the host page.
sequenceDiagram
  participant user as Reader
  participant svc as Service
  participant store as Store

  rect rgb(${r}, ${g}, ${b})
    user->>svc: Request
    svc->>store: Read
    store-->>svc: Rows
    loop Each row
      svc->>svc: Check
    end
    svc-->>user: Answer
  end
`,
);

console.log("build/ updated: tokens.css, tokens.resolved.json, mermaid/ (theme.json, starter.mmd, sequence-starter.mmd, theme-screen-light.json, theme-screen-dark.json)");
